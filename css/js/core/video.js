  function isoWalk(data, cb) {
    // cb(type, pos, size, hdrLen, path) ; return false to skip children
    var view = new DataView(data.buffer, data.byteOffset, data.byteLength);
    var n = data.length;
    var path = [];
    (function walk(start, end) {
      var pos = start;
      while (pos + 8 <= end) {
        var size = view.getUint32(pos, false);
        var hdr = 8;
        if (size === 1) {
          if (pos + 16 > end) break;
          try { size = Number(view.getBigUint64(pos + 8, false)); } catch (e) { break; }
          hdr = 16;
        } else if (size === 0) {
          size = end - pos;
        }
        if (size < hdr || pos + size > end) break;
        var type = fourcc(data, pos + 4);
        var go = cb(type, pos, size, hdr, path);
        if (go !== false && ISO_CONTAINERS[type]) {
          path.push(type);
          // meta 为 FullBox(+4 v/f); iinf 为 FullBox + 2 字节 entry_count
          var childOff = (type === 'meta') ? 4 : (type === 'iinf') ? 6 : 0;
          walk(pos + hdr + childOff, pos + size);
          path.pop();
        }
        pos += size;
      }
    })(0, n);
  }
  function isoStrip(data) {
    var regions = [], removed = [];
    isoWalk(data, function (type, pos, size, hdr) {
      if (type === 'udta' || type === 'meta') {
        regions.push([pos, size]);
        removed.push('MP4:' + type);
        return false; // 整盒零化, 无需深入
      }
      // 含 C2PA 标记的 uuid 盒(规范要求可安全忽略)一并零化
      if (type === 'uuid' && size - hdr >= 4 &&
          (indexOfBytes(data.subarray(pos + hdr, pos + size), 'c2pa') >= 0 ||
           indexOfBytes(data.subarray(pos + hdr, pos + size), 'jumd') >= 0)) {
        regions.push([pos, size]);
        removed.push('MP4:uuid(c2pa)');
        return false;
      }
      return true;
    });
    if (!regions.length) return { data: null, removed: [] };
    var out = new Uint8Array(data.length);
    out.set(data);
    for (var r = 0; r < regions.length; r++) {
      var p = regions[r][0], sz = regions[r][1];
      out[p] = 0x66; out[p + 1] = 0x72; out[p + 2] = 0x65; out[p + 3] = 0x65; // 'free'
      for (var i = p + 4; i < p + sz; i++) out[i] = 0;
    }
    var uniq = {};
    var rem = [];
    for (var u = 0; u < removed.length; u++) if (!uniq[removed[u]]) { uniq[removed[u]] = 1; rem.push(removed[u]); }
    return { data: out, removed: rem };
  }
  function parseDataBox(data, p, sz) {
    // ilst 'data' 子盒存在两种真实布局:
    // A(ffmpeg): type(4) + locale(4) + value        -> value 在 p+16
    // B(Apple):  v/f(4) + type(4) + locale(4) + value -> value 在 p+20
    var a0 = u32(data, p + 8), a1 = u32(data, p + 12);
    var dtyp = 0, off = p + 16, len = sz - 16;
    if ((a0 === 1 || a0 === 13 || a0 === 14 || a0 === 21 || a0 === 27) && a1 === 0) {
      dtyp = a0;
    } else if (a0 === 0 && (a1 === 1 || a1 === 13 || a1 === 14 || a1 === 21 || a1 === 27)) {
      dtyp = a1; off = p + 20; len = sz - 20;
    } else {
      dtyp = a0;
    }
    if (len < 0) len = 0;
    var text = '';
    if (dtyp === 1) text = utf8(data, off, Math.min(len, 2048));
    return { dtyp: dtyp, text: text };
  }
  function isoScan(data, out) {
    out.kind = 'isobmff';
    var view = new DataView(data.buffer, data.byteOffset, data.byteLength);
    var keys = [];
    isoWalk(data, function (type, pos, size, hdr, path) {
      var depth = path.length;
      // 尺寸与时长
      if (type === 'mvhd' && size >= hdr + 20) {
        var ver = data[pos + hdr];
        // v0: v/f(4) ctime(4) mtime(4) timescale(4) duration(4) ...
        // v1: v/f(4) ctime(8) mtime(8) timescale(4) duration(8) ...
        if (ver === 1 && size >= hdr + 32) {
          var ts = view.getUint32(pos + hdr + 20, false), dur = Number(view.getBigUint64(pos + hdr + 24, false));
        } else if (size >= hdr + 20) {
          var ts = view.getUint32(pos + hdr + 12, false), dur = view.getUint32(pos + hdr + 16, false);
        }
        if (ts && !out.duration) out.duration = Math.round(dur / ts * 100) / 100;
        return false;
      }
      if (type === 'tkhd' && size >= hdr + 84) {
        var ver1 = data[pos + hdr];
        var wOff = (ver1 === 1) ? hdr + 88 : hdr + 76;
        if (size >= wOff + 8) {
          var w = view.getUint32(pos + wOff, false) / 65536;
          var h2 = view.getUint32(pos + wOff + 4, false) / 65536;
          out.width = Math.max(out.width || 0, w | 0);
          out.height = Math.max(out.height || 0, h2 | 0);
        }
        return false;
      }
      // keys box(QuickTime metadata keys)
      if (type === 'keys' && path[path.length - 1] === 'meta') {
        try {
          var cnt = u32(data, pos + hdr + 4), off = pos + hdr + 8;
          for (var i = 0; i < Math.min(cnt, 64); i++) {
            if (off + 8 > pos + size) break;
            var klen = u32(data, off);
            // 条目 = size(4) + namespace(4, 'mdta') + value(klen-8), 即整条 klen 字节
            if (off + klen > pos + size) break;
            keys.push(utf8(data, off + 8, klen - 8));
            off += klen;
          }
        } catch (e) {}
        return false;
      }
      // ilst 条目
      if (depth >= 1 && path[depth - 1] === 'ilst' && size >= hdr) {
        var name = ILST_NAMES[type];
        var isCustom = (type === '----');
        var isCprt = (type === 'cprt');
        if (name || isCustom) {
          var text = '';
          var binary = false;
          if (isCprt) {
            if (size >= hdr + 6) text = utf8(data, pos + hdr + 6, size - hdr - 6);
          } else if (isCustom) {
            var mean = '', nm = '';
            // 子盒 mean/name/data
            var p2 = pos + hdr, end2 = pos + size;
            while (p2 + 8 <= end2) {
              var sz2 = u32(data, p2), t2 = fourcc(data, p2 + 4);
              if (sz2 < 8 || p2 + sz2 > end2) break;
              if (t2 === 'mean' && sz2 >= 16) mean = utf8(data, p2 + 12, sz2 - 12).replace(/\0+$/, '');
              else if (t2 === 'name' && sz2 >= 16) nm = utf8(data, p2 + 12, sz2 - 12).replace(/\0+$/, '');
              else if (t2 === 'data' && sz2 >= 16) {
                var db = parseDataBox(data, p2, sz2);
                if (db.dtyp === 1) text = db.text;
                else binary = true;
              }
              p2 += sz2;
            }
            name = 'mp4_custom';
            if (mean) keys.unshift(mean + (nm ? '/' + nm : ''));
            if (!text && !binary && mean) text = 'mp4_custom_present';
          } else {
            var p3 = pos + hdr, end3 = pos + size;
            while (p3 + 8 <= end3) {
              var sz3 = u32(data, p3), t3 = fourcc(data, p3 + 4);
              if (sz3 < 8 || p3 + sz3 > end3) break;
              if (t3 === 'data' && sz3 >= 16) {
                var db3 = parseDataBox(data, p3, sz3);
                if (db3.dtyp === 1) text = db3.text;
                else if (db3.dtyp === 13 || db3.dtyp === 14) { binary = true; }
              }
              p3 += sz3;
            }
          }
          if (binary && !text) {
            out.metadata.push({ name: name === 'mp4_custom' ? 'mp4_cover' : name, value: 'binary_data' });
            return true;
          }
          text = trunc(text, 200);
          if (text) {
            out.metadata.push({ name: name, value: text });
            var c = classify(text);
            if (c) out.findings.push({ key: 'MP4:' + type, value: text, kind: c.kind });
          }
        }
        return true;
      }
      // meta/udta 内的其他子盒: uuid(XMP 等)按字符串扫
      if ((depth >= 2 && path[depth - 1] === 'meta' && path[depth - 2] !== 'ilst') ||
          (depth >= 1 && path[depth - 1] === 'udta')) {
        if (type === 'uuid' || type === 'XMP ') {
          var runs = findRuns(data, pos + hdr, size - hdr, 6);
          for (var rr = 0; rr < runs.length; rr++) {
            var c2 = classify(runs[rr]);
            if (c2) out.findings.push({ key: 'MP4:' + type, value: trunc(runs[rr], 120), kind: c2.kind });
          }
        }
        if (type === 'hdlr' && size >= hdr + 12) {
          var hd = latin1(data, pos + hdr + 8, 4);
          if (hd === 'mdir' || hd === 'mdta') out.metadata.push({ name: 'mp4_mdta_handler', value: 'mdta' });
        }
      }
      return true;
    });
    if (keys.length) out.metadata.push({ name: 'mp4_keys', value: trunc(keys.join(' | '), 200) });
  }

  /* ================= EBML (MKV / WebM) ================= */
  function vint(b, o, maxLen) {
    if (o >= b.length) return null;
    var first = b[o];
    if (first === 0) return null;
    var mask = 0x80, len = 1;
    while (len <= (maxLen || 8) && !(first & mask)) { mask >>= 1; len++; }
    if (len > (maxLen || 8)) return null;
    var value = first & (mask - 1);
    for (var i = 1; i < len; i++) {
      if (o + i >= b.length) return null;
      value = value * 256 + b[o + i];
    }
    // canon: 还原标准 matroska 元素 ID 写法(首字节含长度标记), 便于与 0x18538067 等常量比较
    var canon = value + ((0x80 << (7 * (len - 1))) >>> 0);
    return { value: value, len: len, canon: canon };
  }
