  function riffWalk(data, cb) {
    var n = data.length;
    var view = new DataView(data.buffer, data.byteOffset, data.byteLength);
    if (n < 12 || fourcc(data, 0) !== 'RIFF' || fourcc(data, 8) !== 'AVI ') return;
    (function walk(start, end) {
      var pos = start;
      while (pos + 8 <= end) {
        var id = fourcc(data, pos);
        var size = view.getUint32(pos + 4, true);
        var padded = size + (size & 1);
        if (pos + 8 + padded > end) break;
        if (id === 'LIST') {
          var lt = fourcc(data, pos + 8);
          if (cb('LIST', lt, pos, size, 1) !== false) walk(pos + 12, pos + 8 + padded);
        } else {
          cb(id, null, pos, size, 0);
        }
        pos += 8 + padded;
      }
    })(12, Math.min(8 + view.getUint32(4, true), n));
  }
  function riffStrip(data) {
    var regions = [], removed = [];
    riffWalk(data, function (id, listType, pos, size) {
      if (id === 'LIST' && listType === 'INFO') {
        regions.push([pos, size]);
        removed.push('AVI:INFO');
        return false;
      }
      return true;
    });
    if (!regions.length) return { data: null, removed: [] };
    var out = new Uint8Array(data.length);
    out.set(data);
    for (var r = 0; r < regions.length; r++) {
      var p = regions[r][0], sz = regions[r][1];
      out[p] = 0x4A; out[p + 1] = 0x55; out[p + 2] = 0x4E; out[p + 3] = 0x4B; // 'JUNK'
      for (var i = p + 8; i < p + 8 + sz; i++) out[i] = 0;
    }
    return { data: out, removed: ['AVI:INFO'] };
  }
  function riffScan(data, out) {
    out.kind = 'riff';
    var view = new DataView(data.buffer, data.byteOffset, data.byteLength);
    riffWalk(data, function (id, listType, pos, size, isList) {
      if (isList && listType === 'INFO') {
        // INFO 子块
        var p = pos + 12, end = pos + 8 + size;
        while (p + 8 <= end) {
          var cid = fourcc(data, p);
          var csz = view.getUint32(p + 4, true);
          var cp = csz + (csz & 1);
          if (p + 8 + cp > end) break;
          var text = utf8(data, p + 8, Math.min(csz, 200)).replace(/\0+$/, '');
          var names = { INAM: 'avi_title', IART: 'avi_artist', ICMT: 'avi_comment', ICRD: 'avi_date', ISFT: 'avi_encoder', IENG: 'avi_engineer', ICOP: 'avi_copyright', ITCH: 'avi_technician', IKEY: 'avi_keywords' };
          var nm = names[cid];
          if (nm) {
            out.metadata.push({ name: nm, value: trunc(text, 200) });
            var c = classify(text);
            if (c) out.findings.push({ key: 'AVI:' + cid, value: trunc(text, 120), kind: c.kind });
          }
          p += 8 + cp;
        }
        return false;
      }
      if (!isList && id === 'avih') {
        if (size >= 40) {
          var frames = view.getUint32(pos + 8 + 16, true);
          var usPer = view.getUint32(pos + 8 + 0, true);
          out.width = Math.max(out.width || 0, view.getUint32(pos + 8 + 32, true));
          out.height = Math.max(out.height || 0, view.getUint32(pos + 8 + 36, true));
          if (!out.duration && usPer) out.duration = Math.round(frames * usPer / 10000) / 100;
        }
        return false;
      }
      return true;
    });
  }

