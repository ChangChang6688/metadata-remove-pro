  var VIDEO_EXT = { mp4: 1, mov: 1, m4v: 1, mkv: 1, webm: 1, avi: 1 };
  function detectKind(data) {
    if (data.length >= 12 && fourcc(data, 0) === 'RIFF') {
      if (fourcc(data, 8) === 'AVI ') return 'riff';
      return null;
    }
    if (data.length >= 4 && u32(data, 0) === 0x1A45DFA3) return 'ebml';
    // ISOBMFF: 头部通常为 ftyp/…/moov/mdat/wide/free 之一
    if (data.length >= 12) {
      var t = fourcc(data, 4);
      if (t === 'ftyp' || t === 'moov' || t === 'mdat' || t === 'free' || t === 'skip' || t === 'wide' || t === 'styp' || t === 'pdin') {
        var sz = u32(data, 0);
        if (sz >= 8 && sz <= data.length) return 'isobmff';
      }
    }
    return null;
  }
  function stripVideo(data, ext) {
    var kind = detectKind(data);
    if (!kind) return { data: null, removed: [], kind: null };
    if (kind === 'isobmff') { var r1 = isoStrip(data); return { data: r1.data, removed: r1.removed, kind: kind }; }
    if (kind === 'ebml') { var r2 = ebmlStrip(data); return { data: r2.data, removed: r2.removed, kind: kind }; }
    if (kind === 'riff') { var r3 = riffStrip(data); return { data: r3.data, removed: r3.removed, kind: kind }; }
    return { data: null, removed: [], kind: kind };
  }
  function scanVideo(data, ext) {
    var out = { verdict: 'clean', findings: [], metadata: [], c2pa: false, width: 0, height: 0, duration: 0, kind: null };
    scanC2pa(data, out);
    var kind = detectKind(data);
    if (kind === 'isobmff') isoScan(data, out);
    else if (kind === 'ebml') ebmlScan(data, out);
    else if (kind === 'riff') riffScan(data, out);
    out.verdict = verdictOf(out);
    return out;
  }
  function isVideoExt(ext) { return !!VIDEO_EXT[String(ext || '').toLowerCase()]; }

