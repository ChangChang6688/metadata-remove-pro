  function ebmlWalk(data, start, end, depth, cb) {
    var pos = start;
    while (pos < end) {
      var id = vint(data, pos, 4);
      if (!id) return;
      var sp = vint(data, pos + id.len, 8);
      if (!sp) return;
      var size = sp.value, sizeLen = sp.len, unknown = false;
      if (size === 0xFFFFFFFFFFFFFFFFFF || size === 0x7FFFFFFFFFFFFFFF || size === (Math.pow(2, 7 * sizeLen) - 1)) {
        // 未知大小(全 1): 按到末尾处理(仅 Segment/Cluster 合法)
        size = end - pos - id.len - sizeLen; unknown = true;
      }
      var total = id.len + sizeLen + size;
      if (pos + total > end) return;
      var stop = cb(id.canon, pos, total, id.len, sizeLen, size, depth, unknown);
      if (stop !== false && EBML_CONTAINERS[id.canon]) ebmlWalk(data, pos + id.len + sizeLen, pos + total, depth + 1, cb);
      pos += total;
    }
  }
  // 构造恰好占 totalLen 字节的 Void 元素头(0xEC + size + 全零负载)
  function voidHeader(totalLen) {
    if (totalLen < 2) return null;
    var sizeLen = 1, value = totalLen - 2;
    // vint size 长度随数值大小变化, 迭代收敛
    for (var i = 0; i < 4; i++) {
      var v2 = totalLen - 1 - sizeLen;
      var l2 = vintSize(v2);
      if (l2 === sizeLen) { value = v2; break; }
      sizeLen = l2; value = v2;
    }
    var head = new Uint8Array(1 + sizeLen);
    head[0] = 0xEC;
    var v = value;
    for (var j = sizeLen - 1; j >= 0; j--) { head[1 + j] = v & 0xFF; v = Math.floor(v / 256); }
    head[1] = head[1] | (0x80 >> (sizeLen - 1));
    return head;
  }
  function vintSize(value) {
    // 1 字节 vint 存 7 位, n 字节存 7n 位
    var len = 1;
    while (value > Math.pow(2, 7 * len) - 1) len++;
    return len;
  }
  function ebmlStrip(data) {
    var regions = [], removed = [];
    if (data.length < 4 || u32(data, 0) !== 0x1A45DFA3) return null;
    // 找到 Segment 起点
    var segStart = -1, segEnd = data.length;
    var pos = 0;
    while (pos + 2 <= data.length) {
      var hid = vint(data, pos, 4);
      if (!hid) break;
      var hsp = vint(data, pos + hid.len, 8);
      if (!hsp) break;
      if (hid.canon === 0x18538067) {
        segStart = pos;
        var sz = hsp.value;
        var allOnes = true;
        for (var q = 0; q < hsp.len; q++) if (data[pos + hid.len + q] !== 0xFF) { allOnes = false; break; }
        if (!allOnes && pos + hid.len + hsp.len + sz <= data.length) segEnd = pos + hid.len + hsp.len + sz;
        break;
      }
      var t2 = hid.len + hsp.len + hsp.value;
      if (t2 <= 0 || pos + t2 > data.length) break;
      pos += t2;
    }
    if (segStart < 0) return { data: null, removed: [] };
    ebmlWalk(data, segStart + 0, segEnd, 0, function (id, pos2, total, idLen, sizeLen, size) {
      if (id === 0x1254C367) { // Tags
        regions.push([pos2, total]);
        removed.push('MKV:Tags');
        return false;
      }
      if (id === 0x7BA9 || id === 0x4461) { // Info/Title, Info/DateUTC
        regions.push([pos2, total]);
        removed.push(id === 0x7BA9 ? 'MKV:Title' : 'MKV:DateUTC');
        return false;
      }
      if (id === 0x1941A469) { // Attachments(封面/附件)
        regions.push([pos2, total]);
        removed.push('MKV:Attachments');
        return false;
      }
      return true;
    });
    if (!regions.length) return { data: null, removed: [] };
    var out = new Uint8Array(data.length);
    out.set(data);
    var failed = 0;
    for (var r = 0; r < regions.length; r++) {
      var p = regions[r][0], total3 = regions[r][1];
      var head = voidHeader(total3);
      if (!head || head.length > total3) { failed++; continue; }
      out.set(head, p);
      for (var i2 = p + head.length; i2 < p + total3; i2++) out[i2] = 0;
    }
    var uniq = {}, rem = [];
    for (var u2 = 0; u2 < removed.length; u2++) if (!uniq[removed[u2]]) { uniq[removed[u2]] = 1; rem.push(removed[u2]); }
    return { data: (failed === regions.length) ? null : out, removed: rem };
  }
  function ebmlScan(data, out) {
    out.kind = 'ebml';
    if (data.length < 4 || u32(data, 0) !== 0x1A45DFA3) return;
    var ts = 1000000, durationNs = null;
    var tags = [];
    function readFloat(p, n) {
      if (n === 4) return new DataView(data.buffer, data.byteOffset + p, 4).getFloat32(0, false);
      if (n === 8) return new DataView(data.buffer, data.byteOffset + p, 8).getFloat64(0, false);
      return 0;
    }
    function readUint(p, n) {
      var v = 0;
      for (var i = 0; i < n && p + i < data.length; i++) v = v * 256 + data[p + i];
      return v;
    }
    ebmlWalk(data, 0, data.length, 0, function (id, pos2, total, idLen, sizeLen, size, depth) {
      var payload = pos2 + idLen + sizeLen;
      if (id === 0x2AD7B1 && size >= 1) { ts = readUint(payload, Math.min(size, 8)) || 1000000; return false; }
      if (id === 0x4489 && size >= 4) { durationNs = readFloat(payload, Math.min(size, 8)); return false; }
      if (id === 0x7BA9 && size >= 1) {
        var t = trunc(utf8(data, payload, size), 200);
        out.metadata.push({ name: 'mkv_title', value: t });
        var c = classify(t);
        if (c) out.findings.push({ key: 'MKV:Title', value: t, kind: c.kind });
        return false;
      }
      if (id === 0x4461 && size >= 8) {
        // Matroska DateUTC: 自 2001-01-01 起的纳秒(有符号)
        var neg = (data[payload] & 0x80) !== 0;
        var ns = 0;
        for (var i = 0; i < 8; i++) ns = ns * 256 + data[payload + i];
        if (neg) ns -= Math.pow(2, 64);
        var dt = new Date(978307200000 + Math.round(ns / 1000000));
        if (!isNaN(dt.getTime())) out.metadata.push({ name: 'mkv_creation_time', value: dt.toISOString().slice(0, 19).replace('T', ' ') });
        return false;
      }
      if (id === 0x45A3 && size >= 1) { tags.push('name:' + trunc(utf8(data, payload, size), 80)); return false; }
      if (id === 0x4487 && size >= 1) {
        var tv = trunc(utf8(data, payload, size), 200);
        out.metadata.push({ name: 'mkv_tag', value: tv });
        var c2 = classify(tv);
        if (c2) out.findings.push({ key: 'MKV:Tag', value: tv, kind: c2.kind });
        return false;
      }
      if (id === 0x4485 && size >= 1) { out.metadata.push({ name: 'mkv_tag_binary', value: size + ' B' }); return false; }
      if (id === 0x4D80 && size >= 1) {
        var ma = trunc(utf8(data, payload, size), 120);
        out.metadata.push({ name: 'mkv_muxing_app', value: ma });
        var c3 = classify(ma);
        if (c3) out.findings.push({ key: 'MKV:MuxingApp', value: ma, kind: c3.kind });
        return false;
      }
      if (id === 0x5741 && size >= 1) {
        var wa = trunc(utf8(data, payload, size), 120);
        out.metadata.push({ name: 'mkv_writing_app', value: wa });
        var c4 = classify(wa);
        if (c4) out.findings.push({ key: 'MKV:WritingApp', value: wa, kind: c4.kind });
        return false;
      }
      if (id === 0xB0 && size >= 1) { out.width = Math.max(out.width || 0, readUint(payload, Math.min(size, 8))); return false; }
      if (id === 0xBA && size >= 1) { out.height = Math.max(out.height || 0, readUint(payload, Math.min(size, 8))); return false; }
      return true;
    });
    if (durationNs != null) out.duration = Math.round(durationNs * ts / 1000000000 * 100) / 100;
    if (tags.length) out.metadata.push({ name: 'mkv_tag_names', value: trunc(tags.join(' | '), 160) });
  }

