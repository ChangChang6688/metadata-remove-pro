  function indexOfBytes(haystack, needle) {
    var nl = needle.length;
    if (!nl || haystack.length < nl) return -1;
    for (var i = 0; i <= haystack.length - nl; i++) {
      var ok = true;
      for (var j = 0; j < nl; j++) if (haystack[i + j] !== needle.charCodeAt(j)) { ok = false; break; }
      if (ok) return i;
    }
    return -1;
  }
  function concat(parts) {
    var total = 0;
    for (var i = 0; i < parts.length; i++) total += parts[i].length;
    var out = new Uint8Array(total), off = 0;
    for (var j = 0; j < parts.length; j++) { out.set(parts[j], off); off += parts[j].length; }
    return out;
  }
