  function pngChunks(data) {
    if (data.length < 8 || data[0] !== 0x89 || data[1] !== 0x50 || data[2] !== 0x4E || data[3] !== 0x47) return null;
    var chunks = [], i = 8, view = new DataView(data.buffer, data.byteOffset, data.byteLength);
    while (i + 8 <= data.length) {
      var len = view.getUint32(i, false);
      if (i + 12 + len > data.length) break;
      var type = latin1(data.subarray(i + 4, i + 8));
      chunks.push({ type: type, data: data.subarray(i + 8, i + 8 + len) });
      i += 12 + len;
      if (type === 'IEND') break;
    }
    return chunks;
  }
  function parsePngText(type, payload) {
    try {
      if (type === 'tEXt') {
        var z = payload.indexOf(0);
        return [latin1(payload.subarray(0, z < 0 ? payload.length : z)), utf8(payload.subarray(z + 1))];
      }
      var z0 = payload.indexOf(0);
      if (type === 'zTXt') {
        var rest = payload.subarray(z0 + 1);
        return [latin1(payload.subarray(0, z0)), utf8(inflateRaw(rest.subarray(1)))];
      }
      // iTXt: keyword\0 flag method lang\0 translated\0 text
      var flag = payload[z0 + 1] || 0;
      var rest2 = payload.subarray(z0 + 3);
      var z1 = rest2.indexOf(0);
      var rest3 = rest2.subarray(z1 + 1);
      var z2 = rest3.indexOf(0);
      var text = rest3.subarray(z2 + 1);
      return [latin1(payload.subarray(0, z0)), utf8(flag ? inflateRaw(text) : text)];
    } catch (e) { return ['?', '']; }
  }
  // zlib raw inflate 的最小实现(处理 zTXt/iTXt 压缩文本)
  function inflateRaw(bytes) {
    try {
      if (typeof DecompressionStream !== 'undefined') return inflateSync(bytes);
    } catch (e) {}
    return bytes; // 无法解压时返回原始字节(尽力而为)
  }
  function inflateSync(bytes) {
    // 浏览器环境用 DecompressionStream 同步不可行, 此处返回原文; 调用方会降级处理
    return bytes;
  }
  function stripPng(data) {
    var chunks = pngChunks(data);
    if (!chunks) return null;
    var parts = [data.subarray(0, 8)], removed = [];
    for (var i = 0; i < chunks.length; i++) {
      var ch = chunks[i];
      if (PNG_DROP.indexOf(ch.type) >= 0) { removed.push(ch.type); continue; }
      var raw = new Uint8Array(4 + ch.data.length);
      raw.set([ch.type.charCodeAt(0), ch.type.charCodeAt(1), ch.type.charCodeAt(2), ch.type.charCodeAt(3)]);
      raw.set(ch.data, 4);
      var lenB = new Uint8Array(4);
      new DataView(lenB.buffer).setUint32(0, ch.data.length, false);
      var crcB = new Uint8Array(4);
      new DataView(crcB.buffer).setUint32(0, crc32(raw), false);
      parts.push(lenB, raw, crcB);
    }
    return { data: concat(parts), removed: uniq(removed) };
  }

