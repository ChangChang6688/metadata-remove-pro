  function jpegSegments(data) {
    if (data.length < 4 || data[0] !== 0xFF || data[1] !== 0xD8) return null;
    var segs = [], i = 2;
    while (i + 4 <= data.length) {
      if (data[i] !== 0xFF) break;
      var m = data[i + 1];
      if (m === 0xD8 || (m >= 0xD0 && m <= 0xD7)) { segs.push({ marker: m, data: new Uint8Array(0), offset: i }); i += 2; continue; }
      var len = (data[i + 2] << 8) | data[i + 3];
      if (i + 2 + len > data.length) break;
      segs.push({ marker: m, data: data.subarray(i + 4, i + 2 + len), offset: i });
      i += 2 + len;
      if (m === 0xDA) break;
    }
    return segs;
  }
  function tiffOrientation(tiff) {
    try {
      if (tiff.length < 10) return 1;
      var little = tiff[0] === 0x49 && tiff[1] === 0x49;
      if (!little && !(tiff[0] === 0x4D && tiff[1] === 0x4D)) return 1;
      var view = new DataView(tiff.buffer, tiff.byteOffset, tiff.byteLength);
      var off = view.getUint32(4, little);
      var n = view.getUint16(off, little);
      for (var i = 0; i < Math.min(n, 64); i++) {
        var e = off + 2 + i * 12;
        if (e + 12 > tiff.length) break;
        var tag = view.getUint16(e, little);
        if (tag === 0x0112) {
          var v = view.getUint16(e + 8, little);
          return (v >= 1 && v <= 8) ? v : 1;
        }
      }
    } catch (e) {}
    return 1;
  }
  function minimalApp1(orientation) {
    if (orientation < 2 || orientation > 8) return null;
    var tiff = new Uint8Array(26);
    tiff.set([0x49, 0x49, 0x2A, 0x00, 0x08, 0x00, 0x00, 0x00]);
    tiff[8] = 1; tiff[9] = 0;
    tiff[10] = 0x12; tiff[11] = 0x01; tiff[12] = 3; tiff[13] = 0; tiff[14] = 1; tiff[15] = 0; tiff[16] = 0; tiff[17] = 0;
    tiff[18] = orientation & 0xFF; tiff[19] = (orientation >> 8) & 0xFF;
    tiff[20] = 0; tiff[21] = 0; tiff[22] = 0; tiff[23] = 0; tiff[24] = 0; tiff[25] = 0;
    var payload = new Uint8Array(6 + tiff.length);
    payload.set([0x45, 0x78, 0x69, 0x66, 0x00, 0x00]); payload.set(tiff, 6);
    var seg = new Uint8Array(4 + payload.length);
    seg[0] = 0xFF; seg[1] = 0xE1;
    seg[2] = ((payload.length + 2) >> 8) & 0xFF; seg[3] = (payload.length + 2) & 0xFF;
    seg.set(payload, 4);
    return seg;
  }
  function stripJpeg(data) {
    if (data.length < 4 || data[0] !== 0xFF || data[1] !== 0xD8) return null;
    var orient = 1;
    var segs = jpegSegments(data);
    if (segs) {
      for (var s = 0; s < segs.length; s++) {
        if (segs[s].marker === 0xE1 && segs[s].data.length > 6 &&
            segs[s].data[0] === 0x45 && segs[s].data[1] === 0x78 && segs[s].data[2] === 0x69 && segs[s].data[3] === 0x66) {
          orient = tiffOrientation(segs[s].data.subarray(6));
          break;
        }
      }
    }
    var parts = [data.subarray(0, 2)], removed = [];
    var o1 = minimalApp1(orient);
    if (o1) parts.push(o1);
    var i = 2;
    while (i + 4 <= data.length) {
      if (data[i] !== 0xFF) break;
      var m = data[i + 1];
      if (m === 0xD8 || (m >= 0xD0 && m <= 0xD7)) { parts.push(data.subarray(i, i + 2)); i += 2; continue; }
      var len = (data[i + 2] << 8) | data[i + 3];
      if (i + 2 + len > data.length) break;
      if (m === 0xDA) { parts.push(data.subarray(i)); i = data.length; break; }
      if (m >= 0xE0 && m <= 0xEF) removed.push('APP' + (m - 0xE0));
      else if (m === 0xFE) removed.push('COM');
      else parts.push(data.subarray(i, i + 2 + len));
      i += 2 + len;
    }
    var out = concat(parts);
    if (out.length < 2 || out[out.length - 1] !== 0xD9 || out[out.length - 2] !== 0xFF) {
      var tail = new Uint8Array(2); tail[0] = 0xFF; tail[1] = 0xD9;
      parts.push(tail); out = concat(parts);
    }
    return { data: out, removed: uniq(removed) };
  }

