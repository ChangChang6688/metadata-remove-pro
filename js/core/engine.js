  function webpChunks(data) {
    if (data.length < 12 || data[0] !== 0x52 || data[1] !== 0x49 || data[2] !== 0x46 || data[3] !== 0x46) return null;
    if (data[8] !== 0x57 || data[9] !== 0x45 || data[10] !== 0x42 || data[11] !== 0x50) return null;
    var chunks = [], i = 12, view = new DataView(data.buffer, data.byteOffset, data.byteLength);
    while (i + 8 <= data.length) {
      var four = latin1(data.subarray(i, i + 4));
      var len = view.getUint32(i + 4, true);
      var end = i + 8 + len + (len & 1);
      if (end > data.length) break;
      chunks.push({ four: four, data: data.subarray(i + 8, i + 8 + len) });
      i = end;
    }
    return chunks;
  }
  function stripWebp(data) {
    var chunks = webpChunks(data);
    if (!chunks) return null;
    var drop = ['EXIF', 'XMP ', 'ICCP'];
    var flags = { ICCP: 0x20, EXIF: 0x08, 'XMP ': 0x04 };
    var removed = [];
    var parts = [data.subarray(0, 12)];
    var vp8xAt = -1;
    for (var i = 0; i < chunks.length; i++) {
      var ch = chunks[i];
      if (drop.indexOf(ch.four) >= 0) { removed.push(ch.four); continue; }
      if (ch.four === 'VP8X') vp8xAt = parts.length;
      var head = new Uint8Array(8);
      head[0] = ch.four.charCodeAt(0); head[1] = ch.four.charCodeAt(1);
      head[2] = ch.four.charCodeAt(2); head[3] = ch.four.charCodeAt(3);
      new DataView(head.buffer).setUint32(4, ch.data.length, true);
      parts.push(head, ch.data);
      if (ch.data.length & 1) parts.push(new Uint8Array(1));
    }
    var out = concat(parts);
    if (vp8xAt >= 0 && removed.length) {
      // 清除 VP8X 里被摘除块的标志位(vp8xAt 为 head 段位置, flags 字节在其后 8 字节)
      var fpos = 0;
      for (var p = 0; p < parts.length; p++) { if (p === vp8xAt) break; fpos += parts[p].length; }
      var fp = fpos + 8;
      if (out.length > fp) {
        var f = out[fp];
        for (var d = 0; d < removed.length; d++) f &= ~(flags[removed[d]] || 0);
        out[fp] = f & 0xFF;
      }
    }
    new DataView(out.buffer, out.byteOffset, 4).setUint32(0, out.length - 8, true);
    return { data: out, removed: uniq(removed) };
  }

